def seed():
    db = SessionLocal()
    try:
        if db.query(models.CatalogPlant).count() == 0:
            for p in CATALOG_PLANTS:
                db.add(models.CatalogPlant(**p))
            db.commit()
            print(f"Добавлено {len(CATALOG_PLANTS)} растений в каталог")
        else:
            updated = 0
            added = 0
            for p in CATALOG_PLANTS:
                plant = db.query(models.CatalogPlant).filter(
                    models.CatalogPlant.name == p["name"]
                ).first()
                if plant is None:
                    db.add(models.CatalogPlant(**p))
                    added += 1
                elif p.get("image_url") and not plant.image_url.startswith("/uploads/catalog/"):
                    plant.image_url = p["image_url"]
                    updated += 1
            if added or updated:
                db.commit()
                if added:
                    print(f"Добавлено новых растений: {added}")
                if updated:
                    print(f"Обновлено изображений: {updated}")

        # Скачиваем изображения локально для всех растений без локального файла
        plants = db.query(models.CatalogPlant).all()
        downloaded = 0
        for plant in plants:
            if plant.image_url and not plant.image_url.startswith("/uploads/catalog/"):
                local_path = _download_image(plant.id, plant.image_url)
                if local_path:
                    plant.image_url = local_path
                    downloaded += 1
        if downloaded:
            db.commit()
            print(f"Скачано изображений локально: {downloaded}")

        # Всегда пересоздаём дерево диагностики (статичные данные)
        db.query(models.DiagnosticAnswer).delete()
        db.query(models.DiagnosticStep).delete()
        db.commit()
        for step_data in DIAGNOSTIC_TREE:
            db.add(models.DiagnosticStep(
                id=step_data["id"],
                question=step_data["question"],
                is_root=step_data["is_root"],
            ))
        db.commit()
        for ans_data in DIAGNOSTIC_ANSWERS:
            db.add(models.DiagnosticAnswer(**ans_data))
        db.commit()
        print(f"Диагностика: {len(DIAGNOSTIC_TREE)} шагов, {len(DIAGNOSTIC_ANSWERS)} ответов")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
