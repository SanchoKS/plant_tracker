DATA_DIR = os.environ.get("DATA_DIR", ".")
CATALOG_IMG_DIR = os.path.join(DATA_DIR, "uploads", "catalog")


def _download_image(plant_id: int, url: str) -> str | None:
    """Download image from url, save locally, return local path or None on failure."""
    os.makedirs(CATALOG_IMG_DIR, exist_ok=True)
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
            resp = urllib.request.urlopen(req, timeout=20)
            content_type = resp.headers.get("Content-Type", "image/jpeg")
            ext = ".png" if "png" in content_type else ".jpg"
            filename = f"plant_{plant_id}{ext}"
            with open(os.path.join(CATALOG_IMG_DIR, filename), "wb") as f:
                f.write(resp.read())
            time.sleep(2)
            return f"/uploads/catalog/{filename}"
        except Exception:
            if attempt < 2:
                time.sleep(5 * (attempt + 1))
    return None

